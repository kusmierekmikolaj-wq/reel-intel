"""platforms.py - test matrix: scan real public links per platform and write docs/PLATFORMS.md.

  reel-intel platforms [--urls FILE] [--out FILE]
FILE: one public link per line (# comments allowed). Every link is scanned in a throwaway data folder (audio only), so the
table says what really works today with the installed yt-dlp, instead of what a list of supported sites suggests.
"""
import datetime as dt
import json
import os
import re
import shutil
import statistics as st
import subprocess
import sys
import tempfile
import time
from pathlib import Path

PLATFORMS = [("Instagram Reels", r"instagram\.com"), ("TikTok", r"tiktok\.com"), ("YouTube Shorts", r"youtube\.com|youtu\.be"),
             ("X (Twitter)", r"(?:twitter|x)\.com"), ("Facebook", r"facebook\.com|fb\.watch")]


def platform_of(url):
    for name, pat in PLATFORMS:
        if re.search(pat, url):
            return name
    return "other"


def check(url):
    tmp = Path(tempfile.mkdtemp(prefix="reel_platform_"))
    t0 = time.time()
    try:
        r = subprocess.run([sys.executable, "-m", "reel_intel.cli", "scan", url], capture_output=True, text=True, encoding="utf-8", errors="replace",
                           env={**os.environ, "REEL_DATA": str(tmp)}, timeout=900)
        feats = list((tmp / "data").glob("*/features.json"))
        out = {"url": url, "platform": platform_of(url), "ok": bool(feats), "secs": round(time.time() - t0, 1), "error": ""}
        if feats:
            f = json.loads(feats[0].read_text(encoding="utf-8"))
            out.update(views=f.get("views"), likes=f.get("likes"), comments=f.get("comments"), words=f.get("word_count"), lang=f.get("language"),
                       date=bool(f.get("upload_date")), speech=bool(f.get("speech_reliable") and f.get("word_count", 0) >= 10))
        else:
            line = next((l for l in (r.stdout + r.stderr).splitlines() if "FAILED" in l or "ERROR" in l), "no output")
            out["error"] = re.sub(r"\s+", " ", line)[:140]
        return out
    except subprocess.TimeoutExpired:
        return {"url": url, "platform": platform_of(url), "ok": False, "secs": round(time.time() - t0, 1), "error": "timeout"}
    finally:
        shutil.rmtree(tmp, ignore_errors=True)


def main(argv=None):
    args = list(sys.argv[1:] if argv is None else argv)

    def pop(name, default):
        if name in args:
            i = args.index(name)
            v = args[i + 1]
            del args[i:i + 2]
            return v
        return default
    src, out = Path(pop("--urls", "docs/platform_urls.txt")), Path(pop("--out", "docs/PLATFORMS.md"))
    urls = [l.strip() for l in src.read_text(encoding="utf-8").splitlines() if l.strip().startswith("http")]
    results = []
    for u in urls:
        r = check(u)
        results.append(r)
        print(f"{'OK  ' if r['ok'] else 'FAIL'} {r['platform']:16s} {r['secs']:>6.1f}s  {u}  {r['error']}", flush=True)
    try:
        import yt_dlp
        ver = yt_dlp.version.__version__
    except Exception:
        ver = "?"
    L = ["# Platform support (tested, not assumed)", "",
         f"Generated by `reel-intel platforms` on {dt.date.today().isoformat()} with yt-dlp {ver}; every link below is a public post of an official account, scanned audio-only in a throwaway folder.", "",
         "| platform | links ok | views / likes / comments / date | speech found | median time | status |", "|---|---|---|---|---|---|"]
    for name, _ in PLATFORMS:
        rs = [r for r in results if r["platform"] == name]
        if not rs:
            continue
        ok = [r for r in rs if r["ok"]]
        fields = " / ".join(f"{sum(1 for r in ok if r.get(k) is not None and r.get(k) is not False)}/{len(ok)}" for k in ("views", "likes", "comments", "date")) if ok else "-"
        speech = f"{sum(1 for r in ok if r.get('speech'))}/{len(ok)}" if ok else "-"
        med = f"{st.median(r['secs'] for r in ok):.0f} s" if ok else "-"
        status = "works" if len(ok) == len(rs) else "partial" if ok else "does not work"
        L.append(f"| {name} | {len(ok)}/{len(rs)} | {fields} | {speech} | {med} | **{status}** |")
    L += ["", "## Per link", "", "| platform | result | time | note |", "|---|---|---|---|"]
    for r in results:
        L.append(f"| {r['platform']} | {'ok' if r['ok'] else 'FAILED'} | {r['secs']:.0f} s | {r['error'] or ('lang ' + str(r.get('lang')) + ', ' + str(r.get('words')) + ' words')} |")
    L += ["", "## Profile listing (how to get many links)", "",
          "| platform | yt-dlp can list a profile? | what to do |", "|---|---|---|",
          "| YouTube | yes (`@channel` -> Shorts) | `reel-intel run https://www.youtube.com/@channel` |",
          "| Instagram, TikTok, Facebook | no (login or anti-bot) | `reel-intel snippet` in your logged-in browser, then `reel-intel run grid.tsv` |",
          "| X | no | paste links or use the snippet |", "",
          "Notes: TikTok needs `curl-cffi` (installed with the package). Some posts need a logged-in session (`cookies.txt`, see README). A platform that changes its pages can break extraction until yt-dlp is updated: run `reel-intel doctor`."]
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(f"written {out}")


if __name__ == "__main__":
    main()
